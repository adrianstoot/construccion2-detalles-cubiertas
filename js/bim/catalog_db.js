/**
 * Gestor reactivo del Catálogo BIM con persistencia local y control de versiones de ficha técnica (Sección 14).
 */
export class BIMCatalogStore {
  constructor() {
    this.storageKey = 'ETSIE_C2_BIM_CATALOG_V1';
    this.products = [];
    this.load();
  }

  load() {
    try {
      const saved = localStorage.getItem(this.storageKey);
      if (saved) {
        const parsed = JSON.parse(saved);
        if (Array.isArray(parsed) && parsed.length >= INITIAL_BIM_PRODUCTS.length) {
          this.products = parsed;
          return;
        }
      }
    } catch (e) {
      console.warn('Cargando catálogo BIM oficial por defecto:', e);
    }
    this.products = JSON.parse(JSON.stringify(INITIAL_BIM_PRODUCTS));
  }

  save() {
    try {
      localStorage.setItem(this.storageKey, JSON.stringify(this.products));
    } catch (e) {
      console.warn('No se pudo guardar en localStorage:', e);
    }
  }

  getAllProducts() {
    return this.products;
  }

  getProductById(id) {
    return this.products.find((p) => p.id === id) || null;
  }

  getProductsByFamily(familyId) {
    if (!familyId || familyId === 'ALL') return this.products;
    return this.products.filter((p) => p.familyId === familyId);
  }

  getProductsByRole(role) {
    return this.products.filter((p) => p.role === role);
  }

  /**
   * Aplica una variante dimensional oficial del fabricante sobre un producto sin inventar medidas arbitrarias (Sección 11).
   */
  applyOfficialVariant(productId, variantId) {
    const prod = this.getProductById(productId);
    if (!prod || !Array.isArray(prod.variants)) return prod;
    const v = prod.variants.find((x) => x.id === variantId);
    if (!v) return prod;

    prod.selectedVariantId = variantId;
    Object.keys(v).forEach((k) => {
      if (k !== 'id' && k !== 'label') {
        if (k in prod.geometry) prod.geometry[k] = v[k];
        if (k in prod.technicalSpecs) prod.technicalSpecs[k] = v[k];
      }
    });
    this.save();
    return prod;
  }

  /**
   * Añade o actualiza un producto manteniendo historial de versión de ficha técnica (Sección 14).
   */
  upsertProduct(newProd) {
    const idx = this.products.findIndex((p) => p.id === newProd.id);
    if (idx >= 0) {
      const prev = this.products[idx];
      const history = prev.versionHistory || [];
      history.push({
        savedAt: new Date().toISOString(),
        versionDoc: prev.versionDoc,
        geometry: JSON.parse(JSON.stringify(prev.geometry)),
      });
      newProd.versionHistory = history;
      this.products[idx] = newProd;
    } else {
      this.products.push(newProd);
    }
    this.save();
    return newProd;
  }
}
